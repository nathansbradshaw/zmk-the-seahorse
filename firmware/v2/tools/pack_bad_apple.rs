//! Dependency-free 56x42 / 12 fps gray8 -> monochrome LZSS converter.
use std::{
    collections::HashMap,
    env, fs,
    io::{self, Read, Write},
};
const WIDTH: usize = 56;
const HEIGHT: usize = 42;

fn encode(input: &[u8]) -> Vec<u8> {
    let mut dict: HashMap<[u8; 3], Vec<usize>> = HashMap::new();
    let mut output = Vec::new();
    let mut pos = 0;
    while pos < input.len() {
        let flag_pos = output.len();
        output.push(0);
        for bit in 0..8 {
            if pos == input.len() {
                break;
            }
            let mut best = (0, 0);
            if pos + 3 <= input.len() {
                let key = [input[pos], input[pos + 1], input[pos + 2]];
                if let Some(candidates) = dict.get(&key) {
                    for &old in candidates.iter().rev().take(64) {
                        if pos - old > 4096 {
                            break;
                        }
                        let mut count = 3;
                        while count < 273
                            && pos + count < input.len()
                            && input[old + count] == input[pos + count]
                        {
                            count += 1;
                        }
                        if count > best.0 {
                            best = (count, pos - old);
                        }
                        if count == 273 {
                            break;
                        }
                    }
                }
            }
            let advance;
            if best.0 >= 3 {
                let token = (((best.1 - 1) << 4) | (best.0 - 3).min(15)) as u16;
                output.extend_from_slice(&token.to_le_bytes());
                if best.0 >= 18 {
                    output.push((best.0 - 18) as u8);
                }
                advance = best.0;
            } else {
                output[flag_pos] |= 1 << bit;
                output.push(input[pos]);
                advance = 1;
            }
            for i in pos..pos + advance {
                if i + 3 <= input.len() {
                    let items = dict
                        .entry([input[i], input[i + 1], input[i + 2]])
                        .or_default();
                    if items.len() == 128 {
                        items.drain(..64);
                    }
                    items.push(i);
                }
            }
            pos += advance;
        }
    }
    output
}

fn decode(input: &[u8], length: usize) -> Option<Vec<u8>> {
    let mut output = Vec::new();
    let mut pos = 0;
    while output.len() < length {
        let flags = *input.get(pos)?;
        pos += 1;
        for bit in 0..8 {
            if output.len() == length {
                break;
            }
            if flags & (1 << bit) != 0 {
                output.push(*input.get(pos)?);
                pos += 1;
            } else {
                let token = u16::from_le_bytes([*input.get(pos)?, *input.get(pos + 1)?]) as usize;
                pos += 2;
                let distance = (token >> 4) + 1;
                let mut count = (token & 15) + 3;
                if count == 18 {
                    count += *input.get(pos)? as usize;
                    pos += 1;
                }
                if distance > output.len() || output.len() + count > length {
                    return None;
                }
                for _ in 0..count {
                    output.push(output[output.len() - distance]);
                }
            }
        }
    }
    if pos != input.len() {
        return None;
    }
    Some(output)
}

fn main() -> io::Result<()> {
    let output = env::args()
        .nth(1)
        .expect("usage: pack_bad_apple OUTPUT_DIR < gray8.raw");
    let mut gray = Vec::new();
    io::stdin().read_to_end(&mut gray)?;
    assert!(
        !gray.is_empty() && gray.len() % (WIDTH * HEIGHT) == 0,
        "partial/empty raw frame"
    );
    let count = gray.len() / (WIDTH * HEIGHT);
    let mut frames = vec![0; gray.len() / 8];
    for (i, value) in gray.iter().enumerate() {
        if *value >= 128 {
            frames[i / 8] |= 0x80 >> (i % 8);
        }
    }
    let compressed = encode(&frames);
    assert_eq!(
        decode(&compressed, frames.len()).expect("decode failed"),
        frames
    );
    let fingerprint = frames.iter().fold(0xcbf29ce484222325u64, |h, b| {
        (h ^ *b as u64).wrapping_mul(0x100000001b3)
    });
    fs::create_dir_all(&output)?;
    fs::write(format!("{output}/bad_apple.bin"), &compressed)?;
    let mut c = fs::File::create(format!("{output}/bad_apple_data.inc"))?;
    writeln!(
        c,
        "/* Generated by tools/pack_bad_apple.rs; see BAD_APPLE.md. */"
    )?;
    writeln!(c, "#define BAD_APPLE_WIDTH {WIDTH}\n#define BAD_APPLE_HEIGHT {HEIGHT}\n#define BAD_APPLE_FPS 12\n#define BAD_APPLE_FRAMES {count}")?;
    writeln!(c, "static const uint8_t bad_apple_data[] = {{")?;
    for row in compressed.chunks(20) {
        for byte in row {
            write!(c, "0x{byte:02x},")?;
        }
        writeln!(c)?;
    }
    writeln!(c, "}};")?;
    eprintln!("{count} frames, {} compressed bytes; every pixel verified; decoded FNV64 {fingerprint:016x}", compressed.len());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn literals_overlap_and_window_rollover() {
        for bytes in [
            vec![0; 10000],
            (0..13000).map(|x| (x % 251) as u8).collect(),
            (0..99).collect(),
        ] {
            assert_eq!(decode(&encode(&bytes), bytes.len()).unwrap(), bytes);
        }
    }
    #[test]
    fn truncated_and_invalid_back_references() {
        assert!(decode(&[0, 0], 3).is_none());
        assert!(decode(&[0, 0, 0], 3).is_none());
        assert!(decode(&[1], 1).is_none());
    }
}
